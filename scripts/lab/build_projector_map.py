def _table(comp, name, rows):
	t = comp.create('tableDAT', name)
	t.clear()
	for r in rows:
		t.appendRow(r)
	return t


def _resolution(glsl):
	glsl.par.outputresolution = 'custom'
	glsl.par.resolutionw.expr = 'parent().par.Resolution1'
	glsl.par.resolutionh.expr = 'parent().par.Resolution2'


def _pattern(comp):
	glsl = comp.create('glslTOP', 'pattern')
	pixel = comp.create('textDAT', 'pattern_pixel')
	pixel.text = PATTERN
	glsl.par.pixeldat = pixel.name
	glsl.par.format = 'rgba8fixed'
	_resolution(glsl)
	return glsl


