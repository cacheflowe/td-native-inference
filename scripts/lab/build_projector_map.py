def par(page, kind, name, label, default, lo=None, hi=None, menu=None, disabled=False, help=''):
	group = page.appendInt(name, label=label, size=2) if kind == 'WH' else getattr(page, 'append' + kind)(name, label=label)
	defaults = default if isinstance(default, (tuple, list)) else [default] * len(group)
	for p, d in zip(group, defaults):
		if kind not in ('Pulse',):
			p.default = d
			p.val = d
		if lo is not None:
			p.min = p.normMin = lo
			p.clampMin = True
		if hi is not None:
			p.max = p.normMax = hi
			p.clampMax = True
		if menu:
			p.menuNames = [m[0] for m in menu]
			p.menuLabels = [m[1] for m in menu]
			p.default = p.val = default
		if disabled:
			p.enable = False
	return group


