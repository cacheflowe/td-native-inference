"""Build /project1/Components/CapsuleMatte (run inside TD through the bridge's /run).

CapsuleMatte draws a person as tapered capsules between tracked joints (MediaPipe Holistic's or Pose's
joints DAT: `pose_*` names, plus `left_hand_*` / `right_hand_*`) into a matte, in the camera
image's uv space: a steadier, hole-free alternative to a segmentation matte for Projector Map's
matte input. Edit the component in TD like any network; this script only rebuilds it from scratch.

	curl -X POST --data-binary @scripts/lab/build_capsule_matte.py http://127.0.0.1:3031/run
"""

PARENT = '/project1/Components'
NAME = 'CapsuleMatte'
SLOTS = 40

SHADER = '''// Generated by scripts/lab/build_capsule_matte.py: edit it in the component.
// Tapered capsules: uA = (x, y, radius, valid) of each start, uB = (x, y, radius, 0) of each end, in pixels.
uniform vec4 uA[%d];
uniform vec4 uB[%d];
uniform vec4 uStyle;	// x feather (px)
out vec4 fragColor;
void main() {
	vec2 p = vUV.st * uTDOutputInfo.res.zw;
	float f = max(uStyle.x, 0.5);
	float cover = 0.0;
	for (int i = 0; i < %d; i++) {
		if (uA[i].w < 0.5)
			continue;
		vec2 a = uA[i].xy;
		vec2 ab = uB[i].xy - a;
		float t = clamp(dot(p - a, ab) / max(dot(ab, ab), 1e-6), 0.0, 1.0);
		float d = length(p - a - ab * t) - mix(uA[i].z, uB[i].z, t);
		cover = max(cover, 1.0 - smoothstep(-f, f, d));
	}
	fragColor = vec4(vec3(cover), 1.0);
}
''' % (SLOTS, SLOTS, SLOTS)

LOGIC = '''# CapsuleMatte: joints DAT -> capsule segments (pixels) for the shader.
import math

SLOTS = %d
_STATE = {}	# per Script CHOP path; a body size that is smoothed, so a turning body doesn't make the matte flicker

# (start, end, start radius, end radius) in units of the body size; limbs scale with Limb Width
LIMBS = [
	('left_shoulder', 'left_elbow', 0.17, 0.14), ('left_elbow', 'left_wrist', 0.14, 0.11),
	('right_shoulder', 'right_elbow', 0.17, 0.14), ('right_elbow', 'right_wrist', 0.14, 0.11),
	('left_hip', 'left_knee', 0.24, 0.18), ('left_knee', 'left_ankle', 0.18, 0.12),
	('right_hip', 'right_knee', 0.24, 0.18), ('right_knee', 'right_ankle', 0.18, 0.12),
	('left_ankle', 'left_foot_index', 0.11, 0.08), ('left_ankle', 'left_heel', 0.10, 0.08),
	('right_ankle', 'right_foot_index', 0.11, 0.08), ('right_ankle', 'right_heel', 0.10, 0.08),
]
FINGERS = ('thumb', 'index_finger', 'middle_finger', 'ring_finger', 'pinky')


def read_joints(dat, track_id, min_conf):
	"""name -> (x, y) in uv for one track (the lowest id when track_id is 0). pose_ is stripped."""
	if dat is None or dat.numRows < 2:
		return {}
	head = [c.val for c in dat.row(0)]
	try:
		ci, cn, cx, cy = (head.index(n) for n in ('track_id', 'name', 'x', 'y'))
	except ValueError:
		return {}
	cc = head.index('conf') if 'conf' in head else None
	rows = {}
	for r in range(1, dat.numRows):
		tid = int(float(dat[r, ci].val))
		if track_id > 0 and tid != track_id:
			continue
		conf = float(dat[r, cc].val) if cc is not None else 1.0
		if conf < min_conf:
			continue
		rows.setdefault(tid, {})[dat[r, cn].val.replace('pose_', '', 1)] = (float(dat[r, cx].val), float(dat[r, cy].val))
	return rows[min(rows)] if rows else {}


def compute(comp):
	"""(starts, ends): lists of (x, y, radius, valid) in pixels, SLOTS long."""
	w, h = int(comp.par.Resolution1), int(comp.par.Resolution2)
	joints = read_joints(comp.op('in_joints'), int(comp.par.Trackid), float(comp.par.Minconf))

	def pt(name):
		p = joints.get(name)
		return None if p is None else (p[0] * w, p[1] * h)

	def mid(a, b):
		return None if a is None or b is None else ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)

	def dist(a, b):
		return math.hypot(a[0] - b[0], a[1] - b[1])

	ls, rs, lh, rh = pt('left_shoulder'), pt('right_shoulder'), pt('left_hip'), pt('right_hip')
	sm, hm = mid(ls, rs), mid(lh, rh)
	candidates = []
	if ls and rs:
		candidates.append(dist(ls, rs))
	if sm and hm:
		candidates.append(0.8 * dist(sm, hm))	# stays put when the body turns side-on, shoulder width doesn't
	state = _STATE.setdefault(comp.path, {})
	if candidates:
		size = max(candidates)
		keep = float(comp.par.Sizesmoothing)
		state['size'] = size if 'size' not in state else state['size'] * keep + size * (1 - keep)
	segments = []
	if 'size' in state and candidates:
		k = state['size'] * float(comp.par.Bodyscale)
		limb = float(comp.par.Limbwidth)

		def seg(a, b, ra, rb, scale=1.0):
			if a is not None and b is not None:
				segments.append((a, b, ra * k * scale, rb * k * scale))

		seg(sm, hm, 0.5, 0.42, float(comp.par.Torsowidth))
		seg(ls, rs, 0.2, 0.2, float(comp.par.Torsowidth))
		seg(lh, rh, 0.22, 0.22, float(comp.par.Torsowidth))
		ears = mid(pt('left_ear'), pt('right_ear'))
		head = ears or pt('nose')
		if head is not None:
			nose = pt('nose')
			if ears is not None and nose is not None:	# the head sits a little toward the face
				head = (ears[0] + (nose[0] - ears[0]) * 0.25, ears[1] + (nose[1] - ears[1]) * 0.25)
			seg(head, head, 0.3, 0.3, float(comp.par.Headscale))
			seg(sm, head, 0.12, 0.2)
		for a, b, ra, rb in LIMBS:
			seg(pt(a), pt(b), ra, rb, limb)
		detail = bool(comp.par.Handdetail)
		for side in ('left', 'right'):
			wrist = pt(f'{side}_hand_wrist')
			if detail and wrist is not None:
				seg(wrist, pt(f'{side}_hand_middle_finger_mcp'), 0.09, 0.11)
				seg(pt(f'{side}_hand_index_finger_mcp'), pt(f'{side}_hand_pinky_mcp'), 0.06, 0.06)
				for finger in FINGERS:
					seg(pt(f'{side}_hand_{finger}_mcp'), pt(f'{side}_hand_{finger}_tip'), 0.04, 0.028)
			else:
				seg(pt(f'{side}_wrist'), mid(pt(f'{side}_index'), pt(f'{side}_pinky')), 0.12, 0.09, limb)
	segments = segments[:SLOTS]
	starts = [(a[0], a[1], ra, 1.0) for a, b, ra, rb in segments] + [(0.0, 0.0, 0.0, 0.0)] * (SLOTS - len(segments))
	ends = [(b[0], b[1], rb, 0.0) for a, b, ra, rb in segments] + [(0.0, 0.0, 0.0, 0.0)] * (SLOTS - len(segments))
	return starts, ends


def cook(script):
	absTime.frame	# cook every frame: the joints arrive from a DAT the Script CHOP doesn't watch
	comp = script.parent()
	starts, ends = compute(comp)
	script.clear()
	script.numSamples = SLOTS
	for prefix, rows in (('a', starts), ('b', ends)):
		for index, name in enumerate('xyrv'):
			script.appendChan(f'{prefix}_{name}').vals = [row[index] for row in rows]
	return
''' % SLOTS


def par(page, kind, name, label, default, lo=None, hi=None, help=''):
	group = page.appendInt(name, label=label, size=2) if kind == 'WH' else getattr(page, 'append' + kind)(name, label=label)
	defaults = default if isinstance(default, (tuple, list)) else [default] * len(group)
	for p, d in zip(group, defaults):
		p.default = p.val = d
		if lo is not None:
			p.min = p.normMin = lo
			p.clampMin = True
		if hi is not None:
			p.max = p.normMax = hi
			p.clampMax = True
		if help:
			p.help = help
	return group


def build():
	parent_comp = op(PARENT)
	old = parent_comp.op(NAME)
	position = (old.nodeX, old.nodeY) if old else (600, 0)
	if old:
		old.destroy()
	comp = parent_comp.create('baseCOMP', NAME)
	comp.nodeX, comp.nodeY = position

	page = comp.appendCustomPage('Capsules')
	par(page, 'WH', 'Resolution', 'Resolution', (1280, 720), 16, 8192,
		'The camera image\'s size (or its aspect): joints are in image uv, so a different aspect stretches the capsules.')
	par(page, 'Int', 'Trackid', 'Track ID', 0, 0, 100, '0 = the lowest id in the joints DAT.')
	par(page, 'Float', 'Minconf', 'Min Confidence', 0.3, 0.0, 1.0, 'Joints below this are left out, and so are the capsules that need them.')
	par(page, 'Float', 'Bodyscale', 'Body Scale', 1.0, 0.2, 3.0, 'All the radii, together.')
	par(page, 'Float', 'Torsowidth', 'Torso Width', 1.0, 0.2, 3.0)
	par(page, 'Float', 'Limbwidth', 'Limb Width', 1.0, 0.2, 3.0)
	par(page, 'Float', 'Headscale', 'Head Size', 1.0, 0.2, 3.0)
	par(page, 'Toggle', 'Handdetail', 'Hand Detail', 1, help='With Holistic\'s hand joints: a palm and five fingers instead of one blob.')
	par(page, 'Float', 'Feather', 'Feather (px)', 3.0, 0.0, 60.0)
	par(page, 'Float', 'Sizesmoothing', 'Size Smoothing', 0.85, 0.0, 0.99,
		'The body size the radii follow (shoulder width, or the torso length when turned) is smoothed: higher = steadier.')

	comp.create('inDAT', 'in_joints')
	logic = comp.create('textDAT', 'capsule_logic')
	logic.text = LOGIC
	script = comp.create('scriptCHOP', 'segments')
	callbacks = comp.create('textDAT', 'segments_callbacks')
	callbacks.text = "def onCook(scriptOp):\n\top('capsule_logic').module.cook(scriptOp)\n\treturn\n"
	script.par.callbacks = callbacks.name
	starts = comp.create('selectCHOP', 'seg_a')
	starts.par.chop = 'segments'
	starts.par.channames = 'a_x a_y a_r a_v'
	ends = comp.create('selectCHOP', 'seg_b')
	ends.par.chop = 'segments'
	ends.par.channames = 'b_x b_y b_r b_v'

	pixel = comp.create('textDAT', 'matte_pixel')
	pixel.text = SHADER
	glsl = comp.create('glslTOP', 'matte')
	glsl.par.pixeldat = pixel.name
	glsl.par.format = 'rgba8fixed'
	glsl.par.outputresolution = 'custom'
	glsl.par.resolutionw.expr = 'parent().par.Resolution1'
	glsl.par.resolutionh.expr = 'parent().par.Resolution2'
	glsl.par.array = 2
	glsl.par.array0name, glsl.par.array0type, glsl.par.array0chop = 'uA', 'vec4', starts
	glsl.par.array1name, glsl.par.array1type, glsl.par.array1chop = 'uB', 'vec4', ends
	glsl.par.vec0name = 'uStyle'
	glsl.par.vec0valuex.expr = 'parent().par.Feather'
	out = comp.create('outTOP', 'out_matte')
	out.inputConnectors[0].connect(glsl)

	positions = {'in_joints': (0, 0), 'capsule_logic': (0, -150), 'segments': (150, 0), 'segments_callbacks': (150, -150),
		'seg_a': (300, 60), 'seg_b': (300, -60), 'matte': (450, 0), 'matte_pixel': (450, -150), 'out_matte': (600, 0)}
	for name, (x, y) in positions.items():
		comp.op(name).nodeX, comp.op(name).nodeY = x, y
	return comp


comp = build()
print('built', comp.path, comp.errors(recurse=True)[:300])
