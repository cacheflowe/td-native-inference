"""Writes src/Skeletons.gen.h from python/mediapipe_skeletons.py, so the C++ tracker uses the same
keypoint names, bones and matching constants as the Python one. Run after changing a skeleton:

	python cpp/Tracking/tools/gen_skeletons.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'python'))
import mediapipe_skeletons as ms  # noqa: E402

SKELETONS = {
	'COCO_17': ms.COCO_17, 'MP_POSE': ms.MP_POSE, 'MP_HANDS': ms.MP_HANDS, 'MP_FACE': ms.MP_FACE,
	'MP_FACE_DET': ms.MP_FACE_DET, 'MP_HOLISTIC': ms.MP_HOLISTIC, 'MP_HOLISTIC_BODY': ms.MP_HOLISTIC_BODY,
	'RTMW_BODY': ms.RTMW_BODY,
}


def strings(items):
	out, line = [], '\t'
	for s in items:
		piece = f'"{s}", '
		if len(line) + len(piece) > 100:
			out.append(line.rstrip())
			line = '\t'
		line += piece
	out.append(line.rstrip())
	return '\n'.join(out)


def ints(items):
	out, line = [], '\t'
	for v in items:
		piece = f'{v}, '
		if len(line) + len(piece) > 100:
			out.append(line.rstrip())
			line = '\t'
		line += piece
	out.append(line.rstrip())
	return '\n'.join(out)


lines = ['// Generated by tools/gen_skeletons.py from python/mediapipe_skeletons.py. Do not edit.',
	'#pragma once', '#include "Skeleton.h"', '', 'namespace tracking {', 'namespace gen {', '']
for var, sk in SKELETONS.items():
	low = var.lower()
	lines.append(f'inline const char* const {low}_names[] = {{\n{strings(sk.names)}\n}};')
	lines.append(f'inline const int {low}_edges[] = {{\n{ints(v for e in sk.edges for v in e)}\n}};')
	lines.append(f'inline const int {low}_distance[] = {{\n{ints(sk.distance_indices)}\n}};')
	lines.append('')
lines.append('}  // namespace gen')
lines.append('')
for var, sk in SKELETONS.items():
	low = var.lower()
	lines.append(f'inline const Skeleton {var} = makeSkeleton("{sk.name}", gen::{low}_names, {sk.count}, '
		f'gen::{low}_edges, {len(sk.edges)}, gen::{low}_distance, {len(sk.distance_indices)}, '
		f'{sk.max_match_dist!r}, {str(sk.hide_missing).lower()}, {sk.rel_match_dist!r}, {sk.world_count});')
lines += ['', '}  // namespace tracking', '']
out = Path(__file__).resolve().parents[1] / 'src' / 'Skeletons.gen.h'
out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(f'[gen_skeletons] wrote {out} ({len(SKELETONS)} skeletons)')
